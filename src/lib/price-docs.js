/** 从一行文本里提取金额：优先「数字+元/块/R」，其次「数字/H」，最后纯数字 */
function parseAmount(row) {
  for (let i = 0; i < row.length; i++) {
    const s = String(row[i] || '').trim()
    let m = s.match(/(\d+(?:\.\d+)?)\s*(?:元|块|rmb)/i)
    if (!m) m = s.match(/(\d+(?:\.\d+)?)\s*\/\s*[hH]/)
    if (!m) m = s.match(/(\d+(?:\.\d+)?)\s+保\s*\d+/)   // 如「体验版 288 保 888W」
    if (!m) m = s.match(/^(\d+(?:\.\d+)?)$/)
    if (m) return Math.round(Number(m[1]))
  }
  return 0
}

/** 表格行 → 带样式类名的数据；同时统计档位数与起价
 *  k  = 行序号（用于选中比对，必须是数字）
 *  uk = 跨专区唯一的字符串 key（用于 wx:key，避免切专区时复用旧节点）
 */
function packTable(b, prefix) {
  const pre = (prefix || 'sec') + '_'
  const pi = typeof b.priceIndex === 'number' ? b.priceIndex : 0
  let low = null
  b.rows.forEach(function (r) {
    if (pi < 0 || pi >= r.length) return
    // 仅当单元格以「数字 + 计价单位」开头时才认定为价格，避免把 "-5 滴血""= 2 个小紫" 当成价格
    const m = String(r[pi]).trim().match(/^(\d+)\s*(元|R|块)/i)
    if (m) {
      const n = Number(m[1])
      if (low === null || n < low) low = n
    }
  })
  return {
    type: 'table',
    head: b.head || [],
    low: low,
    count: b.rows.length,
    trs: b.rows.map(function (r, ri) {
      return {
        k: ri,
        uk: pre + 'r' + ri,
        label: r.join(' · '),
        price: parseAmount(r),
        cells: r.map(function (c, i) {
          let cls = 'pr-td'
          if (i === pi) cls += ' pr-price'
          else if (i === r.length - 1) cls += ' pr-last'
          return { k: i, uk: pre + 'r' + ri + 'c' + i, text: c, cls: cls }
        })
      }
    })
  }
}

function packSection(s, prefix) {
  const sid = (prefix ? prefix + '_' : '') + (s.id || 'sec')
  const blocks = (s.blocks || []).map(function (b, i) {
    let out
    if (b.type === 'table') out = packTable(b, sid + '_b' + i)
    else out = Object.assign({}, b)
    out.k = i
    out.uk = sid + '_b' + i
    return out
  })
  let rows = 0
  let low = null
  let noteCount = 0
  blocks.forEach(function (b) {
    if (b.type === 'table') {
      rows += b.count
      if (b.low !== null && (low === null || b.low < low)) low = b.low
    }
    if (b.type === 'notes') noteCount += b.items.length
  })
  const parts = []
  if (rows) parts.push(rows + ' 档')
  if (low !== null) parts.push(low + ' 元起')
  if (noteCount) parts.push(noteCount + ' 条须知')
  return {
    id: s.id,
    name: s.name,
    fixedMap: s.fixedMap || '',
    blocks: blocks,
    meta: parts.join(' · ') || '查看详情'
  }
}

function packDoc(doc) {
  if (!doc) return null
  return {
    id: doc.id,
    title: doc.title,
    sub: doc.sub,
    tabs: doc.tabs.map(function (t) {
      return {
        id: t.id,
        name: t.name,
        sections: t.sections.map(function (s) { return packSection(s, doc.id + '_' + t.id) })
      }
    })
  }
}

function findSection(docId, secId, tabId) {
  const doc = DOCS[docId] || DOCS.mjh
  let tab = null
  if (tabId) {
    tab = doc.tabs.filter(function (t) { return t.id === tabId })[0] || null
  }
  if (!tab && secId) {
    doc.tabs.forEach(function (t) {
      if (tab) return
      const hit = t.sections.filter(function (s) { return s.id === secId })[0]
      if (hit) tab = t
    })
  }
  if (!tab) tab = doc.tabs[0]
  const sec = tab.sections.filter(function (s) { return s.id === secId })[0] || tab.sections[0]
  return { docId: doc.id, tabName: tab.name, section: packSection(sec, doc.id + '_' + tab.id) }
}

/* ==================== 统一在每个专区的「下单须知」末尾补一条 ==================== */
const ASSIGN_TIP = '如需指定打手，请点击「咨询客服」。'

;(function injectAssignTip() {
  Object.keys(DOCS).forEach(function (k) {
    const doc = DOCS[k]
    ;(doc.tabs || []).forEach(function (t) {
      ;(t.sections || []).forEach(function (s) {
        const notesBlocks = (s.blocks || []).filter(function (b) { return b.type === 'notes' })
        const last = notesBlocks[notesBlocks.length - 1]
        if (!last || !last.items) return
        if (last.items.indexOf(ASSIGN_TIP) > -1) return
        last.items.push(ASSIGN_TIP)
      })
    })
  })
})()

